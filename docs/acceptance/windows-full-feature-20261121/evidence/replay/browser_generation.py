"""Independent browser tests; isolated Chromium and temporary localhost origin."""
from pathlib import Path
from functools import partial
from http.server import ThreadingHTTPServer, SimpleHTTPRequestHandler
from threading import Thread
import json, time, traceback, zipfile
from playwright.sync_api import sync_playwright, expect

ROOT=Path.cwd().resolve()
REPO=Path('<USERPROFILE>/.codex/worktrees/mms-v0122-acceptance/minecraft-mod-studio')
OUT=ROOT/'outputs/crystal-lab-full-pipeline'
OUT.mkdir(parents=True, exist_ok=False)
results=[]; errors=[]; console=[]
def check(name,condition,detail=None):
    results.append({'name':name,'passed':bool(condition),'detail':detail})
    if not condition: raise AssertionError(name+': '+str(detail))
def download(page,selector,name):
    with page.expect_download(timeout=30000) as info: page.locator(selector).click()
    dest=OUT/name; info.value.save_as(dest); return dest
def export_json(page,name):
    return json.loads(download(page,'#export',name).read_text(encoding='utf-8'))
def export_source(page,name):
    page.locator('#build').click()
    expect(page.locator('#exportFabricSource')).to_be_visible()
    text=page.locator('#dialog').inner_text()
    (OUT/(name+'.dialog.txt')).write_text(text,encoding='utf-8')
    if page.locator('#exportFabricSource').is_disabled():
        page.locator('#dialog input[type=checkbox]').check()
    return download(page,'#exportFabricSource',name)

server=ThreadingHTTPServer(('127.0.0.1',0),partial(SimpleHTTPRequestHandler,directory=str(REPO)))
Thread(target=server.serve_forever,daemon=True).start()
with sync_playwright() as p:
    browser=p.chromium.launch(headless=True)
    context=browser.new_context(viewport={'width':1600,'height':1000},accept_downloads=True)
    page=context.new_page()
    page.on('pageerror',lambda e:errors.append(str(e)))
    page.on('console',lambda m:console.append({'type':m.type,'text':m.text}) if m.type in ['error','warning'] else None)
    page.on('dialog',lambda d:d.accept())
    url=f'http://127.0.0.1:{server.server_port}/Minecraft_Mod_Studio_V19.html'
    try:
        page.goto(url,wait_until='networkidle')
        check('V2.5 loads',page.title()=='Minecraft Mod Studio V2.5')
        initial=export_json(page,'initial-project.json')
        check('default content migrates',len(initial['items'])==4 and len(initial['studio']['blocks'])>=1)
        page.locator('#settings').click()
        fields=page.locator('#dialogBody input')
        fields.nth(0).fill('Crystal Lab Full Pipeline')
        fields.nth(1).fill('crystal_lab')
        page.locator('#dialogOk').click()
        expect(page.locator('#projectBtn')).to_contain_text('Crystal Lab Full Pipeline')
        page.locator('#name').fill('Verified Storm Sword')
        page.locator('#name').press('Tab')
        page.locator('#damage').fill('15')
        page.locator('#damage').press('Tab')
        page.locator('#save').click()
        modified=export_json(page,'edited-project.json')
        sword=modified['items'][0]
        check('properties update through UI',sword['name']=='Verified Storm Sword' and sword['damage']==15 and modified['modId']=='crystal_lab')
        page.reload(wait_until='networkidle')
        expect(page.locator('#name')).to_have_value('Verified Storm Sword')
        loaded=export_json(page,'reloaded-project.json')
        check('local save survives reload',loaded==modified)
        page.locator('#add').click()
        fields=page.locator('#dialogBody input')
        fields.nth(0).fill('Pulse Crystal')
        fields.nth(1).fill('pulse_crystal')
        page.locator('#dialogOk').click()
        expect(page.locator('#registry')).to_have_value('pulse_crystal')
        # Draw a real pixel and verify texture bytes through project export.
        page.locator('#color').fill('#12ab34')
        page.locator('#paint').click(position={'x':8,'y':8})
        drawn=export_json(page,'drawn-project.json')
        added=next(x for x in drawn['items'] if x['id']=='pulse_crystal')
        check('item creation and pixel drawing',len(drawn['items'])==5 and '#12ab34' in added['pixels'])
        page.locator('#undo').click()
        undone=export_json(page,'undo-project.json')
        check('texture undo',next(x for x in undone['items'] if x['id']=='pulse_crystal')['pixels']!=added['pixels'])
        page.locator('#redo').click()
        redone=export_json(page,'redo-project.json')
        check('texture redo',next(x for x in redone['items'] if x['id']=='pulse_crystal')['pixels']==added['pixels'])
        page.locator('#ingredient').select_option('minecraft:diamond')
        page.locator('#craftGrid button').nth(0).click()
        page.locator('#ingredient').select_option('minecraft:iron_ingot')
        page.locator('#craftGrid button').nth(1).click()
        check('horizontal crafting inputs', 'minecraft:diamond' in page.locator('#craftGrid button').nth(0).get_attribute('aria-label') and 'minecraft:iron_ingot' in page.locator('#craftGrid button').nth(1).get_attribute('aria-label'))
        page.locator('#openNodeStudio').click()
        page.locator('#bgFunctionDemo').click()
        page.locator('#bgRun').click()
        simulation=json.loads(page.locator('#bgResult').inner_text())
        check('function graph simulation computes nested call',simulation['success'] and simulation['variables']['power']==8 and ['heal',8] in simulation['effects'],simulation)
        page.locator('#bgDebugStart').click()
        frames=[]
        for _ in range(12):
            state=json.loads(page.locator('#bgDebugState').inner_text())
            frames.append(state)
            if state.get('stack'):break
            page.locator('#bgDebugInto').click()
        check('debugger steps into real function frames',bool(state.get('stack')),state)
        page.locator('#bgDebugContinue').click()
        state=json.loads(page.locator('#bgDebugState').inner_text())
        check('debugger completes with expected variable',state.get('kind')=='finished' and state.get('variables',{}).get('power')==8,state)
        (OUT/'function-debugger.json').write_text(json.dumps({'simulation':simulation,'steps':frames,'final':state},ensure_ascii=False,indent=2),encoding='utf-8')
        page.screenshot(path=str(OUT/'02-function-graph.png'),full_page=True)
        (OUT/'node-dialog.txt').write_text(page.locator('#bgDialog').inner_text(),encoding='utf-8')
        page.locator('#bgApply').click()
        expect(page.locator('#bgDialog')).not_to_be_visible()
        page.locator('#studioNav button[data-open=blocks]').click()
        page.locator('#add').click()
        fields=page.locator('#dialogBody input')
        fields.nth(0).fill('Pulse Block')
        fields.nth(1).fill('pulse_block')
        page.locator('#dialogOk').click()
        expect(page.locator('[data-edit=id]')).to_have_value('pulse_block')
        page.locator('[data-edit=hardness]').fill('3')
        page.locator('[data-edit=hardness]').press('Tab')
        drop=page.locator('[data-edit=drop] option').filter(has_text='Pulse Crystal')
        check('custom block drop target present',drop.count()==1,page.locator('[data-edit=drop] option').all_text_contents())
        page.locator('[data-edit=drop]').select_option(value=drop.get_attribute('value'))
        page.locator('[data-edit=dropCount]').fill('2')
        page.locator('[data-edit=dropCount]').press('Tab')
        graphed=export_json(page,'function-project.json')
        new_block=next(x for x in graphed['studio']['blocks'] if x['id']=='pulse_block')
        check('custom block generated in browser',new_block['name']=='Pulse Block' and new_block['hardness']==3,new_block)
        graph=next(x for x in graphed['items'] if x['id']=='pulse_crystal').get('graph')
        check('Node Studio function graph applies',bool(graph and graph.get('functions')))
        page.locator('#test').click()
        validation=page.locator('#validationCard').inner_text()
        check('project validation', 'Validation passed' in validation,validation)
        page.locator('#save').click()
        page.screenshot(path=str(OUT/'03-edited-project.png'),full_page=True)
        export_source(page,'crystal-lab-fabric-source.zip')
        with zipfile.ZipFile(OUT/'crystal-lab-fabric-source.zip') as z:
            source=z.read('studio-project.json').decode()
            exported=json.loads(source)
            check('source ZIP preserves edited items and graph',exported['items']==graphed['items'] and exported['modId']==graphed['modId'] and exported['name']==graphed['name'])
            check('source ZIP CRC valid',z.testzip() is None)
            recipe=json.loads(z.read('src/main/resources/data/crystal_lab/recipe/pulse_crystal.json'))
            check('real generated custom recipe',recipe['pattern']==['AB'] and list(recipe['key'].values())==['minecraft:diamond','minecraft:iron_ingot'] and recipe['result']['id']=='crystal_lab:pulse_crystal',recipe)
            for target in ('assets/crystal_lab/textures/item/pulse_crystal.png','assets/crystal_lab/blockstates/pulse_block.json','data/crystal_lab/loot_table/blocks/pulse_block.json'):
                check('generated '+target, 'src/main/resources/'+target in z.namelist())
            source_dir=OUT/'fabric-project'
            for item in z.infolist():
                candidate=(source_dir/item.filename).resolve()
                if not candidate.is_relative_to(source_dir.resolve()): raise AssertionError('unsafe ZIP member')
            z.extractall(source_dir)
        # Open a second, clean context to validate file import rather than shared storage.
        second=browser.new_context(viewport={'width':1600,'height':1000},accept_downloads=True)
        imported=second.new_page()
        imported.on('pageerror',lambda e:errors.append(str(e)))
        imported.on('dialog',lambda d:d.accept())
        imported.goto(url,wait_until='networkidle')
        imported.locator('#fileInput').set_input_files(str(OUT/'function-project.json'))
        expect(imported.locator('#projectBtn')).to_contain_text('Crystal Lab Full Pipeline')
        again=export_json(imported,'imported-project.json')
        check('JSON import roundtrip in fresh context',again==graphed)
        bad=OUT/'invalid-project.json';bad.write_text('{broken json',encoding='utf-8')
        imported.locator('#fileInput').set_input_files(str(bad))
        expect(imported.locator('#toast')).to_be_visible()
        after=export_json(imported,'after-invalid-import.json')
        check('invalid JSON rejected atomically',after==again)
        imported.screenshot(path=str(OUT/'04-import-roundtrip.png'),full_page=True)
        second.close()
        check('no uncaught browser exceptions',len(errors)==0,errors)
    except Exception as e:
        results.append({'name':'test execution','passed':False,'detail':traceback.format_exc()})
        page.screenshot(path=str(OUT/'failure.png'),full_page=True)
    finally:
        (OUT/'ui-results.json').write_text(json.dumps({'checks':results,'pageErrors':errors,'console':console},ensure_ascii=False,indent=2),encoding='utf-8')
        print(json.dumps({'checks':results,'errors':errors},ensure_ascii=True))
        browser.close()
server.shutdown()
raise SystemExit(0 if all(x['passed'] for x in results) else 1)
